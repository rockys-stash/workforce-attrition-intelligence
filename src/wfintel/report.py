"""Render docs/generated/results.md from a pipeline result. Every number comes from the result files."""

from __future__ import annotations

import json
import re
from pathlib import Path
from typing import Any

from wfintel.paths import DOCS, RESULTS

MODEL_LABEL = {"prevalence": "Prevalence only (baseline)", "overtime_only": "Overtime only (baseline)",
               "logistic": "Logistic regression (interpretable)", "boosting": "Gradient boosting (reference)"}  # fmt: skip
KEY_FACTORS = ("department", "job_level", "income_band", "pay_position", "tenure_band", "age_band", "overtime",
               "business_travel", "performance_rating", "promotion_band", "job_satisfaction", "work_life_balance",
               "stock_option_level")  # fmt: skip


def pct(v: float | None, d: int = 1) -> str:
    return "–" if v is None else f"{100 * v:.{d}f}%"


def num(v: float | None, d: int = 2) -> str:
    return "–" if v is None else f"{v:,.{d}f}".replace("-", "−")


def pval(p: float) -> str:
    return "< 0.001" if p < 0.001 else f"{p:.3f}"


def table(head: list[str], rows: list[list[str]]) -> str:
    def numeric(i: int) -> bool:
        return all(re.match(r"^[\d−<–]", r[i]) for r in rows if r[i] != "–")

    align = ["---:" if i and numeric(i) else "---" for i in range(len(head))]
    return "\n".join(
        ["| " + " | ".join(head) + " |", "| " + " | ".join(align) + " |"] + ["| " + " | ".join(r) + " |" for r in rows]
    )


def render(results: Path = RESULTS, out: Path | None = None) -> Path:
    rid = (results / "LATEST").read_text(encoding="utf-8").strip()
    d = results / rid

    def load(n: str) -> Any:
        return json.loads((d / f"{n}.json").read_text(encoding="utf-8"))

    ov, q, at, risk, rec, aud, pv = (load(n) for n in ("overview", "quality", "attrition", "risk", "recommendations",
        "audit", "provenance"))  # fmt: skip
    k = ov["kpis"]
    m = risk["model"]
    s = [
        "# Results", "",
        f"Generated by `wfintel report` from `results/{rid}` (commit `{pv['commit'][:7]}`, "
        f"{'clean' if not pv['dirty'] else 'DIRTY'} tree, {pv['runtime_seconds']} s). Do not edit by hand.", "",
        "IBM HR Analytics Employee Attrition & Performance: a fictional dataset. Every figure is an association in "
        "one cross-section of that synthetic workforce.", "",
        "## Data checks", "",
        table(["#", "Check", "Value", "Action"], [[str(c["id"]), c["check_name"], f"{num(c['value'], 0)} {c['unit']}", c["action"]]
                                                 for c in q["data_checks"]]), "",
        table(["Table", "Rows"], [[t["table_name"], f"{t['rows']:,}"] for t in q["model_tables"]]), "",
        "## Headline", "",
        table(["Measure", "Value"], [
            ["Employees", f"{k['employees']:,}"], ["Left", f"{k['leavers']:,}"], ["Attrition rate", pct(k["rate"])],
            ["Median monthly income", f"{k['median_income']:,.0f}"], ["Working overtime", pct(k["overtime_share"])],
            ["Median years at the company", f"{k['median_tenure']:g}"], ["Median age", f"{k['median_age']:g}"]]), "",
        "## Attrition by characteristic", "",
        "Rates with Wilson 95% intervals.", "",
    ]  # fmt: skip
    for f in KEY_FACTORS:
        fac = at["factors"][f]
        s += [f"**{fac['name']}**", "",
              table(["Group", "Employees", "Left", "Rate", "95% CI"],
                    [[x["label"], f"{x['employees']:,}", str(x["leavers"]), pct(x["rate"]), f"{pct(x['ci_low'])}–{pct(x['ci_high'])}"]
                     for x in fac["levels"]]), ""]  # fmt: skip
    roles = sorted(at["factors"]["job_role"]["levels"], key=lambda x: -x["rate"])
    s += ["**Job role**", "", table(["Role", "Employees", "Left", "Rate", "95% CI"],
          [[x["label"], str(x["employees"]), str(x["leavers"]), pct(x["rate"]), f"{pct(x['ci_low'])}–{pct(x['ci_high'])}"] for x in roles]), ""]  # fmt: skip
    s += ["## Association tests", "",
          f"{len(at['tests'])} tests, Holm-corrected; significant = adjusted p < 0.05. Cramér's V for categories; "
          "rank-biserial r for numbers (negative = leavers lower).", "",
          table(["Characteristic", "Test", "Effect size", "p (Holm)", "Significant"],
                [[t["name"], t["test"], f"{t['effect_name']} {num(t['effect'])}", pval(t["p_holm"]), "yes" if t["significant"] else "no"]
                 for t in at["tests"]]), ""]  # fmt: skip
    st = at["stratified"][0]
    s += ["## Overtime within job level", "",
          f"Crude odds ratio {num(st['crude']['odds_ratio'])} ({num(st['crude']['ci'][0])}–{num(st['crude']['ci'][1])}); "
          f"Mantel–Haenszel within job level {num(st['mantel_haenszel']['odds_ratio'])} "
          f"({num(st['mantel_haenszel']['ci'][0])}–{num(st['mantel_haenszel']['ci'][1])}); "
          f"test of equal odds ratios across levels p = {pval(st['homogeneity_p'])}.", "",
          table(["Job level", "Employees", "With overtime", "Rate with", "Rate without", "Odds ratio (95% CI)"],
                [[x["stratum"], str(x["employees"]), str(x["exposed"]), pct(x["rate_exposed"]), pct(x["rate_unexposed"]),
                  f"{num(x['odds_ratio'])} ({num(x['ci'][0])}–{num(x['ci'][1])})"] for x in st["strata"]]), ""]  # fmt: skip
    sp = m["split"]
    s += ["## Model of observed attrition risk", "",
          f"Stratified split: {sp['train']} training employees ({sp['train_leavers']} left), {sp['test']} test employees "
          f"({sp['test_leavers']} left), seed {sp['seed']}. Regularisation C = {m['c']:g}, chosen by 5-fold cross-validated "
          "log loss on the training part only; the test part was scored once. 95% bootstrap intervals over test employees.", "",
          table(["Model", "AUROC", "Average precision", "Brier", "Calibration intercept", "Calibration slope"],
                [[MODEL_LABEL[n], f"{num(v['auroc'], 3)} [{num(m['bootstrap']['models'][n]['auroc'][0], 3)}, {num(m['bootstrap']['models'][n]['auroc'][1], 3)}]",
                  f"{num(v['average_precision'], 3)} [{num(m['bootstrap']['models'][n]['average_precision'][0], 3)}, {num(m['bootstrap']['models'][n]['average_precision'][1], 3)}]",
                  num(v["brier"], 3), num(v["calibration_intercept"]), num(v["calibration_slope"])]
                 for n, v in m["test"].items()]), "",
          "AUROC of logistic regression minus each other model (paired bootstrap):", "",
          table(["Compared with", "Difference", "95% CI"],
                [[MODEL_LABEL[n], num(x["diff"], 3), f"{num(x['ci'][0], 3)} to {num(x['ci'][1], 3)}"]
                 for n, x in m["bootstrap"]["auroc_diff_logistic_minus"].items()]), "",
          f"Out-of-fold (all {k['employees']:,} employees, 5 folds): AUROC {num(m['oof_metrics']['auroc'], 3)}, "
          f"calibration slope {num(m['oof_metrics']['calibration_slope'])}. Without stock option level: test AUROC "
          f"{num(m['without_stock_options']['test']['auroc'], 3)}, out-of-fold {num(m['without_stock_options']['oof_metrics']['auroc'], 3)}.", "",
          "### Adjusted odds ratios", "",
          f"Unpenalised logistic regression on all employees (pseudo-R² {num(m['odds_ratios']['pseudo_r2'])}). Each odds ratio "
          "is the association with having left, holding the other listed variables fixed; it is not the result of changing "
          "the variable. Reference categories: " + ", ".join(f"{c.replace('_', ' ')} = {v}" for c, v in m["odds_ratios"]["reference_levels"].items()) + ".", "",
          table(["Term", "Odds ratio", "95% CI", "p"],
                [[t["label"], num(t["odds_ratio"]), f"{num(t['ci'][0])}–{num(t['ci'][1])}", pval(t["p"])] for t in m["odds_ratios"]["terms"]]), "",
          "Variance inflation (numeric terms): " + ", ".join(f"{c.replace('_', ' ')} {v:.1f}" for c, v in m["odds_ratios"]["vif"].items() if v >= 2.5)
          + "; all others below 2.5.", ""]  # fmt: skip
    rs = risk["risk_segments"]
    s += ["## Risk segments (out-of-fold predicted risk)", "",
          table(["Band", "Predicted risk", "Employees", "Left", "Observed rate", "Mean predicted", "Overtime", "Median income", "Median tenure"],
                [[b["band"], f"{pct(b['range'][0], 0)}–{pct(b['range'][1], 0)}", str(b["employees"]), str(b["leavers"]), pct(b["rate"]),
                  pct(b["mean_predicted"]), pct(b["overtime_share"], 0), f"{b['median_income']:,.0f}", f"{b['median_tenure']:g}"]
                 for b in rs["bands"]]), ""]  # fmt: skip
    sg = risk["segments"]
    s += ["## Workforce segments (k-means)", "",
          f"k = {sg['k']} by silhouette (" + ", ".join(f"{kk}: {v:.3f}" for kk, v in sg["silhouette"].items()) + "); "
          f"agreement with refits from five other seeds (adjusted Rand) {min(sg['stability_ari']):.2f}–{max(sg['stability_ari']):.2f}.", "",
          table(["Segment", "Profile", "Employees", "Left", "Rate", "95% CI", "Median age", "Median income", "Overtime"],
                [[str(x["segment"]), x["label"], str(x["employees"]), str(x["leavers"]), pct(x["rate"]), f"{pct(x['ci'][0])}–{pct(x['ci'][1])}",
                  f"{x['median_age']:g}", f"{x['median_income']:,.0f}", pct(x["overtime_share"], 0)] for x in sg["segments"]]), ""]  # fmt: skip

    def fair(rows: list[dict[str, Any]]) -> str:
        return table(["Attribute", "Group", "Employees", "Observed rate", "Mean predicted", "AUROC", "Flagged high", "True positive rate", "False positive rate"],
                     [[x["attribute"].replace("_", " "), x["group"], str(x["employees"]), pct(x["observed_rate"]), pct(x["mean_predicted"]),
                       num(x["auroc"], 3), pct(x["flagged_share"]), pct(x["true_positive_rate"]), pct(x["false_positive_rate"])] for x in rows])  # fmt: skip

    s += ["## Fairness check (out-of-fold)", "", "\"Flagged high\" = predicted risk in the High band.", "", fair(risk["fairness"]), "",
          "Without stock option level:", "", fair(risk["fairness_without_stock_options"]), ""]  # fmt: skip
    s += ["## Recommendations", ""]
    for i, r in enumerate(rec["recommendations"], 1):
        s += [f"{i}. **{r['title']}** ({r['area']}). {r['finding']} Evidence: " + "; ".join(e.rstrip(".") for e in r["evidence"])
              + f". Action: {r['action']} Basis: {r['basis']}"]  # fmt: skip
    s += [
        "",
        "## Causal-language audit",
        "",
        f"{'PASS' if aud['passed'] else 'FAIL'}: {len(aud['files'])} files and texts scanned against {len(aud['rules'])} rules, "
        f"{len(aud['findings'])} finding{'' if len(aud['findings']) == 1 else 's'} (audit run with the pipeline; `wfintel audit` reruns it on the current files).",
        "",
    ]
    out = out or DOCS / "generated" / "results.md"
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text("\n".join(s), encoding="utf-8")
    return out
